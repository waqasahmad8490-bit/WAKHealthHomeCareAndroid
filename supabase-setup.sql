-- WAK Health & Home Care Business Management System
-- Run once in Supabase Dashboard > SQL Editor. Review before production use.
create extension if not exists pgcrypto;

create table if not exists public.wak_staff (
 id uuid primary key default gen_random_uuid(),
 user_id uuid unique references auth.users(id) on delete cascade,
 full_name text not null,
 email text,
 phone text,
 role text not null default 'nurse' check (role in ('admin','receptionist','nurse','physiotherapist','doctor','finance')),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.wak_patients (
 id uuid primary key default gen_random_uuid(),
 full_name text not null,
 phone text not null,
 age integer check (age is null or age between 0 and 120),
 gender text,
 area text,
 address text,
 emergency_contact text,
 notes text,
 created_by uuid default auth.uid(),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.wak_appointments (
 id uuid primary key default gen_random_uuid(),
 patient_id uuid references public.wak_patients(id) on delete set null,
 patient_name text,
 phone text,
 service text not null default 'Home Nursing',
 scheduled_at timestamptz not null,
 address text,
 assigned_staff_id uuid references public.wak_staff(id) on delete set null,
 status text not null default 'pending' check (status in ('pending','confirmed','in_progress','completed','cancelled')),
 notes text,
 created_at timestamptz not null default now()
);
create table if not exists public.wak_cases (
 id uuid primary key default gen_random_uuid(),
 patient_id uuid references public.wak_patients(id) on delete cascade,
 case_type text not null check (case_type in ('nursing','physiotherapy','family physician','other')),
 diagnosis_or_goal text,
 care_plan text,
 start_date date default current_date,
 end_date date,
 sessions_planned integer,
 sessions_completed integer not null default 0,
 assigned_staff_id uuid references public.wak_staff(id) on delete set null,
 status text not null default 'active' check (status in ('active','on_hold','completed','closed')),
 notes text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.wak_transactions (
 id uuid primary key default gen_random_uuid(),
 transaction_date date not null default current_date,
 kind text not null check (kind in ('income','expense','staff_payment','refund')),
 category text not null,
 amount numeric(12,2) not null check (amount > 0),
 patient_id uuid references public.wak_patients(id) on delete set null,
 staff_id uuid references public.wak_staff(id) on delete set null,
 payment_method text default 'cash',
 description text,
 recorded_by uuid default auth.uid(),
 created_at timestamptz not null default now()
);
create table if not exists public.wak_booking_requests (
 id uuid primary key default gen_random_uuid(),
 full_name text not null,
 phone text not null,
 service text not null,
 preferred_date date,
 preferred_time text,
 area text,
 address text,
 message text,
 status text not null default 'new' check (status in ('new','contacted','scheduled','completed','declined')),
 created_at timestamptz not null default now()
);
create table if not exists public.wak_updates (
 id bigint generated by default as identity primary key,
 category text not null default 'Announcement', title text not null, description text not null,
 link_url text, link_text text, file_url text, file_name text,
 is_published boolean not null default false, published_at timestamptz,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create or replace function public.wak_my_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.wak_staff where user_id=auth.uid() and active=true limit 1; $$;
create or replace function public.wak_is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.wak_my_role()='admin', false); $$;
create or replace function public.wak_is_reception()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.wak_my_role() in ('admin','receptionist','finance'), false); $$;
create or replace function public.wak_can_see_patient(pid uuid)
returns boolean language sql stable security definer set search_path=public
as $$ select public.wak_is_reception() or exists (
 select 1 from public.wak_cases c join public.wak_staff s on s.id=c.assigned_staff_id
 where c.patient_id=pid and s.user_id=auth.uid() and s.active=true
); $$;
revoke all on function public.wak_my_role() from public;
revoke all on function public.wak_is_admin() from public;
revoke all on function public.wak_is_reception() from public;
revoke all on function public.wak_can_see_patient(uuid) from public;
grant execute on function public.wak_my_role() to authenticated;
grant execute on function public.wak_is_admin() to authenticated, anon;
grant execute on function public.wak_is_reception() to authenticated;
grant execute on function public.wak_can_see_patient(uuid) to authenticated;

alter table public.wak_staff enable row level security;
alter table public.wak_patients enable row level security;
alter table public.wak_appointments enable row level security;
alter table public.wak_cases enable row level security;
alter table public.wak_transactions enable row level security;
alter table public.wak_booking_requests enable row level security;
alter table public.wak_updates enable row level security;

grant select on public.wak_staff to authenticated;
grant insert,update,delete on public.wak_staff to authenticated;
grant select,insert,update,delete on public.wak_patients to authenticated;
grant select,insert,update,delete on public.wak_appointments to authenticated;
grant select,insert,update,delete on public.wak_cases to authenticated;
grant select,insert,update,delete on public.wak_transactions to authenticated;
grant select,update,delete on public.wak_booking_requests to authenticated;
grant insert on public.wak_booking_requests to anon,authenticated;
grant select on public.wak_updates to anon,authenticated;
grant insert,update,delete on public.wak_updates to authenticated;

-- Staff can read their own profile; only admins can manage staff and assign roles.
drop policy if exists staff_read on public.wak_staff;
create policy staff_read on public.wak_staff for select to authenticated using (user_id=auth.uid() or public.wak_is_admin());
drop policy if exists staff_admin_manage on public.wak_staff;
create policy staff_admin_manage on public.wak_staff for all to authenticated using (public.wak_is_admin()) with check (public.wak_is_admin());

-- Patient records: admin/reception/finance manage; clinicians only see assigned patients.
drop policy if exists patients_read on public.wak_patients;
create policy patients_read on public.wak_patients for select to authenticated using (public.wak_can_see_patient(id));
drop policy if exists patients_reception_insert on public.wak_patients;
create policy patients_reception_insert on public.wak_patients for insert to authenticated with check (public.wak_is_reception());
drop policy if exists patients_reception_update on public.wak_patients;
create policy patients_reception_update on public.wak_patients for update to authenticated using (public.wak_is_reception()) with check (public.wak_is_reception());
drop policy if exists patients_admin_delete on public.wak_patients;
create policy patients_admin_delete on public.wak_patients for delete to authenticated using (public.wak_is_admin());

-- Appointments: front desk manages; assigned clinical staff can see/update their own visits.
drop policy if exists appointments_read on public.wak_appointments;
create policy appointments_read on public.wak_appointments for select to authenticated using (
 public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true));
drop policy if exists appointments_reception_insert on public.wak_appointments;
create policy appointments_reception_insert on public.wak_appointments for insert to authenticated with check (public.wak_is_reception());
drop policy if exists appointments_update on public.wak_appointments;
create policy appointments_update on public.wak_appointments for update to authenticated using (
 public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true)) with check (
 public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true));
drop policy if exists appointments_admin_delete on public.wak_appointments;
create policy appointments_admin_delete on public.wak_appointments for delete to authenticated using (public.wak_is_admin());

-- Clinical cases: front desk/admin can manage; clinician sees only assigned cases.
drop policy if exists cases_read on public.wak_cases;
create policy cases_read on public.wak_cases for select to authenticated using (public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true));
drop policy if exists cases_reception_insert on public.wak_cases;
create policy cases_reception_insert on public.wak_cases for insert to authenticated with check (public.wak_is_reception());
drop policy if exists cases_update on public.wak_cases;
create policy cases_update on public.wak_cases for update to authenticated using (public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true)) with check (public.wak_is_reception() or exists(select 1 from public.wak_staff s where s.id=assigned_staff_id and s.user_id=auth.uid() and s.active=true));
drop policy if exists cases_admin_delete on public.wak_cases;
create policy cases_admin_delete on public.wak_cases for delete to authenticated using (public.wak_is_admin());

-- Finance is hidden from clinicians; admin/reception/finance roles can manage it.
drop policy if exists transactions_read on public.wak_transactions;
create policy transactions_read on public.wak_transactions for select to authenticated using (public.wak_is_reception());
drop policy if exists transactions_insert on public.wak_transactions;
create policy transactions_insert on public.wak_transactions for insert to authenticated with check (public.wak_is_reception());
drop policy if exists transactions_update on public.wak_transactions;
create policy transactions_update on public.wak_transactions for update to authenticated using (public.wak_is_reception()) with check (public.wak_is_reception());
drop policy if exists transactions_delete on public.wak_transactions;
create policy transactions_delete on public.wak_transactions for delete to authenticated using (public.wak_is_admin());

-- Public website can submit a booking request, but cannot read or edit any request.
drop policy if exists booking_public_insert on public.wak_booking_requests;
create policy booking_public_insert on public.wak_booking_requests for insert to anon,authenticated with check (length(trim(full_name)) between 2 and 120 and length(trim(phone)) between 7 and 30 and length(trim(service)) between 2 and 100);
drop policy if exists booking_staff_read on public.wak_booking_requests;
create policy booking_staff_read on public.wak_booking_requests for select to authenticated using (public.wak_is_reception());
drop policy if exists booking_staff_update on public.wak_booking_requests;
create policy booking_staff_update on public.wak_booking_requests for update to authenticated using (public.wak_is_reception()) with check (public.wak_is_reception());
drop policy if exists booking_admin_delete on public.wak_booking_requests;
create policy booking_admin_delete on public.wak_booking_requests for delete to authenticated using (public.wak_is_admin());

-- Published notice board is public; drafts and editing are admin-only.
drop policy if exists updates_public_read on public.wak_updates;
create policy updates_public_read on public.wak_updates for select to anon,authenticated using (is_published=true or public.wak_is_admin());
drop policy if exists updates_admin_insert on public.wak_updates;
create policy updates_admin_insert on public.wak_updates for insert to authenticated with check (public.wak_is_admin());
drop policy if exists updates_admin_update on public.wak_updates;
create policy updates_admin_update on public.wak_updates for update to authenticated using (public.wak_is_admin()) with check (public.wak_is_admin());
drop policy if exists updates_admin_delete on public.wak_updates;
create policy updates_admin_delete on public.wak_updates for delete to authenticated using (public.wak_is_admin());

